// G2: story.json -> script.json. Counts words programmatically and plans timing at the bible's planning pace.
// Planned timing is a placeholder for layout/animatic only; real timing comes from /spec/vo-manifest.json.
import fs from "node:fs";
import { p } from "../env";
import { syllables, tokenize } from "../lib/words";

const style = JSON.parse(fs.readFileSync(p("spec/style.json"), "utf8"));
const story = JSON.parse(fs.readFileSync(p("spec/story.json"), "utf8"));
const P = style.pacing;

type Line = { id: string; text: string; emotion: string; gag?: number; callbackOf?: number };
const lines: (Line & { beat: number })[] = story.beats.flatMap((b: any) => b.lines.map((l: Line) => ({ ...l, beat: b.beat })));
const tok = lines.map((l) => tokenize(l.text));
const totalWords = tok.reduce((a, t) => a + t.length, 0);
const totalSyl = tok.flat().reduce((a, t) => a + syllables(t.clean), 0);
const speechS = totalWords / P.plannedWps;
const sylRate = totalSyl / speechS; // syllables per second, constant across lines

let t = 0;
const out = lines.map((l, li) => {
  if (li > 0) t += lines[li - 1].beat !== l.beat ? P.beatPauseS : P.linePauseS;
  const start = t;
  const words = tok[li].map((w) => {
    const d = syllables(w.clean) / sylRate;
    const word = { i: w.i, text: w.text, start: +t.toFixed(3), end: +(t + d).toFixed(3) };
    t += d;
    return word;
  });
  return { line: l.id, beat: l.beat, text: l.text, emotion: l.emotion, start: +start.toFixed(3), end: +t.toFixed(3), words: words.length, wps: +(words.length / (t - start)).toFixed(2), tokens: words, ...(l.gag ? { gag: l.gag } : {}), ...(l.callbackOf ? { callbackOf: l.callbackOf } : {}) };
});
// Retime from real narration when an approved VO manifest exists (word starts become the timing truth).
const vo = fs.existsSync(p("spec/vo-manifest.json")) ? JSON.parse(fs.readFileSync(p("spec/vo-manifest.json"), "utf8")) : { status: "missing" };
if (vo.status === "ok") {
  out.forEach((l: any) => {
    const v = vo.lines.find((x: any) => x.line === l.line);
    l.tokens = l.tokens.map((tk: any, k: number) => ({ ...tk, start: v.words[k].start, end: v.words[k].end }));
    l.start = l.tokens[0].start; l.end = l.tokens[l.tokens.length - 1].end; l.wps = +(l.words / (l.end - l.start)).toFixed(2);
  });
  t = out[out.length - 1].end;
}
const lastWordEnd = t;
const duration = lastWordEnd + P.endRoomToneS;

const problems: string[] = [];
if (totalWords < P.voWordsMin || totalWords > P.voWordsMax) problems.push(`total words ${totalWords} outside ${P.voWordsMin}-${P.voWordsMax}`);
for (const l of out) if (l.words > P.maxWordsPerLine) problems.push(`${l.line} has ${l.words} words > ${P.maxWordsPerLine}`);
if (Math.abs(duration - style.format.targetDurationS) > 2) problems.push(`planned duration ${duration.toFixed(2)} s not within 88 +/- 2 s`);
const overallWps = totalWords / lastWordEnd;
if (overallWps < P.wpsMin || overallWps > P.wpsMax) problems.push(`overall wps ${overallWps.toFixed(2)} outside ${P.wpsMin}-${P.wpsMax}`);
for (const g of [1, 2, 3]) {
  const n = out.filter((l) => l.gag === g).reduce((a, l) => a + l.words, 0);
  if (n > 12) problems.push(`gag ${g} has ${n} words > 12`);
}

const beats = story.beats.map((b: any) => {
  const ls = out.filter((l) => l.beat === b.beat);
  const words = ls.reduce((a, l) => a + l.words, 0);
  return { beat: b.beat, name: b.name, targetStart: b.targetStart, targetEnd: b.targetEnd, plannedStart: ls[0].start, plannedEnd: ls[ls.length - 1].end, words };
});

const script = {
  $comment: "GENERATED by tools/spec/build-script.ts from spec/story.json. Times are PLANNED (timing: 'planned') until retimed from vo-manifest.json.",
  title: story.title,
  timing: vo.status === "ok" ? "vo" : "planned",
  plannedWps: P.plannedWps,
  syllablesPerSecond: +sylRate.toFixed(3),
  totalWords,
  overallWps: +overallWps.toFixed(3),
  lastWordEnd: +lastWordEnd.toFixed(3),
  duration: +duration.toFixed(3),
  beats,
  lines: out,
};
fs.writeFileSync(p("spec/script.json"), JSON.stringify(script, null, 2) + "\n");
console.log(JSON.stringify({ totalWords, overallWps: script.overallWps, duration: script.duration, beats: beats.map((b: any) => `${b.beat}:${b.name} ${b.plannedStart.toFixed(1)}-${b.plannedEnd.toFixed(1)} (target ${b.targetStart}-${b.targetEnd}) ${b.words}w`) }, null, 1));
if (problems.length) { console.error("G2 FAIL:\n- " + problems.join("\n- ")); process.exit(1); }
console.log("G2 PASS");
